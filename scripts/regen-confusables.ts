/**
 * Regenerate the Unicode confusables map from a PINNED unicode.org source.
 * Run manually on a Unicode-version bump (NOT on install):
 *   npx tsx scripts/regen-confusables.ts
 */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

// Pin to a specific Unicode security revision (check unicode.org/Public/security/ for newer).
const UNICODE_VERSION = '16.0.0';
const SOURCE_URL = `https://www.unicode.org/Public/security/${UNICODE_VERSION}/confusables.txt`;
// SHA-256 of the fetched body. Leave '' on first run: the script prints the computed hash,
// then paste it here and re-run so future regens are integrity-checked.
const EXPECTED_SHA256 = '95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611';

const OUT_DIR = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'lib',
  'server',
  'user-store'
);

export function sha256Hex(input: string): string {
  return createHash('sha256').update(input, 'utf8').digest('hex');
}

/** Parse confusables.txt → compact { sourceChar: targetString } map. */
export function parseConfusables(content: string): Record<string, string> {
  const map: Record<string, string> = {};
  for (const line of content.split('\n')) {
    if (line.startsWith('#') || line.trim() === '') continue;
    // Format: SRC ; TGT [TGT …] ; MA  # comment
    // Only single-CP sources match; multi-CP sources (e.g. "0308 0301") are skipped.
    const m = line.match(/^([0-9A-Fa-f]+)\s*;\s*([0-9A-Fa-f][0-9A-Fa-f\s]*?)\s*;\s*MA\b/);
    if (!m) continue;
    const source = String.fromCodePoint(parseInt(m[1], 16));
    const target = m[2]
      .trim()
      .split(/\s+/)
      .map((hex) => String.fromCodePoint(parseInt(hex, 16)))
      .join('');
    map[source] = target;
  }
  return map;
}

function extractHeader(content: string, key: string): string {
  const m = content.match(new RegExp(`^#\\s*${key}:\\s*(.+)$`, 'm'));
  return m ? m[1].trim() : 'unknown';
}

export async function runRegenConfusables(): Promise<void> {
  console.log(`📥 Fetching ${SOURCE_URL}`);
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`HTTP ${res.status} ${res.statusText}`);
  const content = await res.text();

  const digest = sha256Hex(content);
  if (EXPECTED_SHA256 && digest !== EXPECTED_SHA256) {
    throw new Error(`SHA-256 mismatch!\n  expected ${EXPECTED_SHA256}\n  got      ${digest}`);
  }
  if (!EXPECTED_SHA256) {
    console.log(
      `ℹ️  No EXPECTED_SHA256 set. Computed: ${digest}\n   Paste this into EXPECTED_SHA256 and re-run.`
    );
  }

  const map = parseConfusables(content);
  const version = extractHeader(content, 'Version');
  const date = extractHeader(content, 'Date');
  console.log(`📊 ${Object.keys(map).length} mappings, Unicode ${version} (${date})`);

  // Sort keys for a stable, reviewable diff.
  const sorted: Record<string, string> = {};
  for (const k of Object.keys(map).sort()) sorted[k] = map[k];

  // Single-quote string literals so the emitted file matches the repo's Prettier config.
  const sq = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

  // Emit the map as a JSON *string* in a `.ts` module (parsed at runtime in
  // confusable-skeleton.ts), NOT as `confusables.json`. A `?raw` JSON import is a Vite-only
  // query the worker esbuild pass doesn't honour — it re-resolves the JSON as an object and
  // the worker then crashes on `JSON.parse([object Object])` at boot. A plain string export
  // is bundler-agnostic and keeps exotic prototype code points quoted (never bare keys).
  const data = `// GENERATED by scripts/regen-confusables.ts — DO NOT EDIT.
export default ${sq(JSON.stringify(sorted))};
`;
  writeFileSync(join(OUT_DIR, 'confusables-data.ts'), data, 'utf8');

  const meta = `// GENERATED by scripts/regen-confusables.ts — DO NOT EDIT.
export const CONFUSABLES_META = {
  unicodeVersion: ${sq(version)},
  date: ${sq(date)},
  sourceUrl: ${sq(SOURCE_URL)},
  sha256: ${sq(digest)},
  mappings: ${Object.keys(sorted).length}
} as const;
`;
  writeFileSync(join(OUT_DIR, 'confusables.meta.ts'), meta, 'utf8');
  console.log('💾 Wrote confusables-data.ts + confusables.meta.ts');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  runRegenConfusables().catch((e) => {
    console.error('❌', e);
    process.exit(1);
  });
}
