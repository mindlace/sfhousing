import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  realpathSync,
  rmSync,
  statSync,
  writeFileSync
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { DATASET_VERSION_RE } from '../../src/lib/data/dataset-version';
import { FIXTURE_PROFILE } from '../config';
import { readLock } from '../lib/lock';
import { build, printResults } from './build';
import { CALIBRATION_JSON, CALIBRATION_REPORT_MD } from './calibration';
import { HISTORIES_JSON, PERMITS_PARQUET, PROJECTS_JSON, dumpPermits } from './projects';
import { POLICY_BIN, POLICY_DUMP, formatPolicyDump, readPolicyBin } from './policy';
import { PARCELS_BIN, SCENARIO_DUMP, formatScenarioDump, readParcelsBin } from './scenario';

const REPO_ROOT = resolve(import.meta.dirname, '../..');
const MINI = join(REPO_ROOT, 'pipeline/test/fixtures/mini');
const E2E = join(REPO_ROOT, 'e2e/fixtures/data/fixture-0');
const GOLDEN = join(MINI, 'golden');
/**
 * Deterministic outputs pinned by golden.test.ts (tile bytes and fonts are not compared). The T11
 * file and policy.bin are pinned by their decoded dumps, SCENARIO_DUMP and POLICY_DUMP, not by
 * their deflate bytes (spec §4.8).
 */
const GOLDEN_FILES = [
  'parcels',
  'manifest.json',
  'neighborhoods.geojson',
  'report.json',
  'transit.json',
  PROJECTS_JSON,
  CALIBRATION_JSON
];
/**
 * Derived-cache outputs pinned by golden.test.ts (project-records spec §4.9), under
 * `golden/derived/`: the histories byte for byte, permits.parquet by its row values, and the
 * calibration report (stage-calibration spec §4.10) byte for byte.
 */
export const GOLDEN_DERIVED = {
  histories: HISTORIES_JSON,
  permits: 'permits.json',
  calibrationReport: CALIBRATION_REPORT_MD
} as const;

const README = `# fixture-0

Generated by \`npm run pipeline -- fixture\` from \`pipeline/test/fixtures/mini/\`. Do not edit these
files by hand: change the mini fixture or the pipeline and regenerate (\`--update-golden\` also
refreshes \`pipeline/test/fixtures/mini/golden/\`). Load it into local R2 with \`npm run data:fixture\`.
`;

export interface FixtureOpts {
  /** Write the dataset here instead of e2e/fixtures/data/fixture-0 (never touches e2e/ or golden). */
  outDir?: string;
  /** Dataset version (default fixture-0); without outDir it goes to pipeline/out/<version>. */
  version?: string;
  skipTiles?: boolean;
  /** Also copy the deterministic outputs into pipeline/test/fixtures/mini/golden/. */
  updateGolden?: boolean;
  /**
   * Derived cache root to keep (outputs land in `<derivedRoot>/<version>/`); default a per-run
   * temp dir that is removed afterwards.
   */
  derivedRoot?: string;
}

function replaceDir(dst: string, src: string, keep: string[] = []): void {
  mkdirSync(dst, { recursive: true });
  for (const e of readdirSync(dst)) {
    if (!keep.includes(e)) rmSync(join(dst, e), { recursive: true, force: true });
  }
  cpSync(src, dst, { recursive: true });
}

const PROTECTED = ['pipeline/test/fixtures', 'e2e/fixtures'].map((d) => join(REPO_ROOT, d));

const within = (p: string, root: string) => {
  const r = relative(root, p);
  return r === '' || (!r.startsWith('..') && !isAbsolute(r));
};

/**
 * Why `fixture` must not write to `dir`, or null when it may. It refuses anything inside the
 * committed fixture trees, and an existing non-empty directory unless it holds a previous fixture
 * output (a manifest.json whose datasetVersion is fixture-<n>), because the target is emptied.
 */
export function outTargetError(dir: string): string | null {
  const abs = existsSync(dir) ? realpathSync(dir) : resolve(dir);
  const hit = PROTECTED.find((p) => within(abs, existsSync(p) ? realpathSync(p) : p));
  if (hit) return `refusing --out ${dir}: inside ${relative(REPO_ROOT, hit)}`;
  if (!existsSync(abs)) return null;
  if (!statSync(abs).isDirectory()) return `refusing --out ${dir}: not a directory`;
  if (readdirSync(abs).length === 0) return null;
  try {
    const m = JSON.parse(readFileSync(join(abs, 'manifest.json'), 'utf8')) as {
      datasetVersion?: unknown;
    };
    if (typeof m.datasetVersion === 'string' && /^fixture-\d+$/.test(m.datasetVersion)) return null;
  } catch {
    // no readable manifest: fall through
  }
  return `refusing --out ${dir}: not empty and not a previous fixture output`;
}

/** Spec §4.2 `fixture`: build the mini fixture; returns the exit code. */
export async function fixture(opts: FixtureOpts = {}): Promise<number> {
  const version = opts.version ?? 'fixture-0';
  if (!DATASET_VERSION_RE.test(version) || !version.startsWith('fixture-')) {
    console.error(`fixture version must be fixture-<n>, got ${version}`);
    return 1;
  }
  const custom = opts.outDir !== undefined || opts.version !== undefined;
  if (custom && opts.updateGolden) {
    console.error('--update-golden only applies to the default fixture-0 output');
    return 1;
  }
  const target = custom ? resolve(opts.outDir ?? join(REPO_ROOT, 'pipeline/out', version)) : E2E;
  const refusal = custom ? outTargetError(target) : null;
  if (refusal) {
    console.error(refusal);
    return 1;
  }
  const lockPath = join(MINI, 'sources.lock.json');
  const newest = Math.max(...readLock(lockPath).sources.map((s) => Date.parse(s.retrievedAt)));
  const outRoot = mkdtempSync(join(tmpdir(), 'sfh-fixture-'));
  const derivedRoot = opts.derivedRoot ?? join(outRoot, 'derived');
  try {
    const { outDir, results } = await build({
      lockPath,
      rawDir: join(MINI, 'raw'),
      rawByName: true,
      outRoot,
      // A per-run derived cache, so parallel fixture builds never share pipeline/.cache/derived.
      derivedRoot,
      datasetVersion: version,
      builtAt: new Date(newest).toISOString(),
      profile: FIXTURE_PROFILE,
      skipTiles: opts.skipTiles
    });
    const code = printResults(results);
    if (code !== 0) return code;
    if (custom) {
      replaceDir(target, outDir);
      return 0;
    }
    replaceDir(E2E, outDir, ['README.md']);
    writeFileSync(join(E2E, 'README.md'), README);
    if (opts.updateGolden) {
      rmSync(GOLDEN, { recursive: true, force: true });
      mkdirSync(GOLDEN, { recursive: true });
      for (const f of GOLDEN_FILES) {
        mkdirSync(dirname(join(GOLDEN, f)), { recursive: true });
        cpSync(join(outDir, f), join(GOLDEN, f), { recursive: true });
      }
      mkdirSync(dirname(join(GOLDEN, SCENARIO_DUMP)), { recursive: true });
      const parcels = readParcelsBin(join(outDir, PARCELS_BIN));
      writeFileSync(join(GOLDEN, SCENARIO_DUMP), formatScenarioDump(parcels));
      writeFileSync(
        join(GOLDEN, POLICY_DUMP),
        formatPolicyDump(readPolicyBin(join(outDir, POLICY_BIN), parcels))
      );
      const derived = join(derivedRoot, version);
      mkdirSync(join(GOLDEN, 'derived'), { recursive: true });
      cpSync(join(derived, HISTORIES_JSON), join(GOLDEN, 'derived', GOLDEN_DERIVED.histories));
      writeFileSync(
        join(GOLDEN, 'derived', GOLDEN_DERIVED.permits),
        await dumpPermits(join(derived, PERMITS_PARQUET))
      );
      cpSync(
        join(derived, CALIBRATION_REPORT_MD),
        join(GOLDEN, 'derived', GOLDEN_DERIVED.calibrationReport)
      );
    }
    return 0;
  } catch (e) {
    console.error(e instanceof Error ? e.message : e);
    return 1;
  } finally {
    rmSync(outRoot, { recursive: true, force: true });
  }
}
